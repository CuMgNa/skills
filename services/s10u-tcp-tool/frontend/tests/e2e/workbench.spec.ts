import { test, expect, type Page } from '@playwright/test'
async function apiPost(page: Page, path: string, body: unknown = {}) {
  return page.evaluate(async ({path,body}) => {
    const {token} = await (await fetch('/api/bootstrap')).json()
    const response = await fetch(`/api${path}`,{method:'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:JSON.stringify(body)})
    if (!response.ok) throw new Error(`${path}: ${await response.text()}`)
    return response.json()
  },{path,body})
}
async function state(page: Page) {
  return page.evaluate(async () => { const {token} = await (await fetch('/api/bootstrap')).json(); return (await fetch('/api/state',{headers:{Authorization:`Bearer ${token}`}})).json() })
}
async function connectPractice(page: Page) {
  await page.getByText('连接选项与本地练习',{exact:true}).click()
  await page.getByTestId('practice-start').click()
  await expect(page.getByTestId('practice-select')).toBeEnabled()
  await page.getByTestId('practice-select').click()
  await page.getByTestId('connect').click()
  await expect(page.getByTestId('send-once')).toBeEnabled()
}
test.beforeEach(async ({page}) => {
  page.on('dialog',dialog => dialog.accept())
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'S10U TCP 调测工具台'})).toBeVisible()
  await apiPost(page,'/disconnect'); await apiPost(page,'/practice/stop')
  await expect(page.getByTestId('connect')).toBeEnabled()
})
test.afterEach(async ({page}) => { await apiPost(page,'/disconnect'); await apiPost(page,'/practice/stop') })
test('manual uplink sends once and refresh never reconnects or sends', async ({page}) => {
  await connectPractice(page)
  await page.getByTestId('preview').click()
  await expect(page.locator('.uplink-form [data-testid="packet-details"]')).toBeVisible()
  const before = await state(page)
  await page.getByTestId('send-once').click()
  await expect.poll(async () => (await state(page)).logs.filter((log: {direction:string;session_id:string}) => log.direction === 'tx' && log.session_id === before.connection.session_id).length).toBe(1)
  const session = (await state(page)).connection.session_id
  await page.reload()
  await expect(page.getByTestId('send-once')).toBeEnabled()
  const after = await state(page)
  expect(after.connection.session_id).toBe(session)
  expect(after.logs.filter((log: {direction:string;session_id:string}) => log.direction === 'tx' && log.session_id === session)).toHaveLength(1)
  await expect(page.getByTestId('environment-select').locator('input')).toBeDisabled()
})
