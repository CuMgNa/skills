test('anomalous raw bytes require explicit confirmation and cancel produces no send', async ({page}) => {
  await connectPractice(page)
  await page.getByText('原始 text / HEX',{exact:true}).click()
  const raw = '[3G*2016001000*0000*LK,0,0,85]'
  await page.getByTestId('raw-input').fill(raw)
  const session = (await state(page)).connection.session_id
  const txCount = async () => (await state(page)).logs.filter((log: {direction:string;session_id:string}) => log.direction === 'tx' && log.session_id === session).length
  const before = await txCount()
  await page.getByTestId('send-once').click()
  await expect(page.getByText('异常报文发送确认',{exact:true})).toBeVisible()
  expect(await txCount()).toBe(before)
  await page.getByRole('button',{name:'取消',exact:true}).click()
  expect(await txCount()).toBe(before)
  await page.getByTestId('send-once').click()
  await expect(page.getByText('异常报文发送确认',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'确认',exact:true}).click()
  await expect.poll(txCount).toBe(before + 1)
  await expect(page.locator('.uplink-form [data-testid="packet-text"]')).toHaveText(raw)
})
test('editing raw input during send leaves returned byte preview visibly stale', async ({page}) => {
  await connectPractice(page)
  const draft = await page.evaluate(async () => (await (await fetch('/api/bootstrap')).json()).metadata.defaults.LK)
  const packet = await apiPost(page,'/preview',{draft})
  await page.getByText('原始 text / HEX',{exact:true}).click()
  await page.getByTestId('raw-input').fill(packet.text)
  let release!: () => void
  const hold = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/send',async route => { const response = await route.fetch(); await hold; await route.fulfill({response}) })
  const request = page.waitForRequest('**/api/send')
  await page.getByTestId('send-once').click(); await request
  try { await page.getByTestId('raw-input').fill('[edited while sending]') } finally { release() }
  await expect(page.getByText('字段已修改，以下预览已过期；发送时会重新编码校验。',{exact:true})).toBeVisible()
  await expect(page.locator('.uplink-form [data-testid="packet-text"]')).toHaveText(packet.text)
  await expect(page.getByTestId('raw-input')).toHaveValue('[edited while sending]')
})
test('real TCP downlink manual reply and old-session send guard plus authenticated export', async ({page}) => {
  await apiPost(page,'/policies/VERNO',{mode:'manual',action:'normal',delay:0,version:'S10U-E2E',raw:'',raw_mode:'text'})
  await connectPractice(page)
  await page.getByRole('tab',{name:'下行接收与回复'}).click()
  await page.getByTestId('practice-command').click()
  await page.getByRole('option',{name:/VERNO/}).click()
  await page.getByTestId('practice-send').click()
  await expect(page.getByTestId('downlink-records').getByRole('row').filter({hasText:'VERNO'}).first()).toBeVisible()
  await page.getByTestId('downlink-records').getByRole('row').filter({hasText:'VERNO'}).last().click()
  await expect(page.getByTestId('reply-record')).toBeEnabled()
  await page.getByTestId('reply-record').click()
  await page.getByRole('button',{name:'确认',exact:true}).click()
  await expect(page.getByTestId('reply-record')).toBeDisabled()
  await page.getByTestId('practice-send').click()
  await expect.poll(async () => (await state(page)).downlinks.filter((r: {status:string;packet:{command:string}}) => r.packet.command === 'VERNO' && r.status === 'pending').length).toBeGreaterThan(0)
  await page.getByTestId('downlink-records').getByRole('row').filter({hasText:'待处理'}).last().click()
  await page.getByTestId('disconnect').click()
  await expect(page.getByTestId('reply-record')).toBeDisabled()
  await expect(page.getByTestId('connect')).toBeEnabled()
  await page.getByTestId('connect').click()
  await expect(page.getByText('这是旧会话接收记录，禁止向当前连接发送回复。',{exact:true})).toBeVisible()
  await expect(page.getByTestId('reply-record')).toBeDisabled()
  const downloadPromise = page.waitForEvent('download')
  await page.getByTestId('export-json').click()
  expect((await downloadPromise).suggestedFilename()).toMatch(/s10u-logs-.*\.json$/)
})
